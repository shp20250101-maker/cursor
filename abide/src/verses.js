/** Day-of-year index (0-based), stable across timezones for local midnight. */
export function dayOfYear(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date - start;
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

export function verseForDate(date = new Date()) {
  const index = dayOfYear(date) % verses.length;
  return { ...verses[index], index };
}

export function storageKeyForDate(date = new Date()) {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `abide-journal-${y}-${m}-${d}`;
}
